/**
 * Return the region for a dataset country name. Unknown names return the
 * safety-net fallback region (the coverage test asserts this never happens for
 * the 183 dataset countries).
 * @param {string} countryName Dataset `countryname` value.
 * @returns {string}
 */
export function getRegion(countryName) {
  return COUNTRY_REGION[countryName] ?? FALLBACK_REGION;
}

/**
 * Return the Spanish display name for a dataset country key, falling back to
 * the raw dataset name when no translation is registered.
 * @param {string} countryName Dataset `countryname` value (stable id).
 * @returns {string}
 */
export function getDisplayName(countryName) {
  return COUNTRY_DISPLAY_NAME[countryName] ?? countryName;
}

/**
 * Group dataset country names by region.
 * @param {string[]} countryNames
 * @returns {Record<string, string[]>}
 */
export function groupByRegion(countryNames) {
  /** @type {Record<string, string[]>} */
  const grouped = {};
  for (const name of countryNames) {
    const region = getRegion(name);
    (grouped[region] ??= []).push(name);
  }
  return grouped;
}
